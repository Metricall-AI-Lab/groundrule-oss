// CodeRabbit as a sync target (RFC 0010): the rulebook writes `.coderabbit.yaml`, so the
// reviewer reads the same rules as the agents. Groundrule owns only its own entries in that
// file (marked with a sentinel), and leaves everything the team wrote alone, comments included.
//
// Two kinds of entry:
// - `reviews.path_instructions`: one per scope group, the rules as review guidance for the
//   files they cover (the same grouping as the Cursor and Copilot files).
// - `reviews.pre_merge_checks.custom_checks`: CodeRabbit's AI pass/fail checks, for rules that
//   no deterministic check covers (AI review or guidance) at blocker or warning severity, at
//   most five (CodeRabbit's limit), highest severity first. Always `warning`: AI never blocks a
//   change on its own (the product principle behind the "AI review (advisory)" label).

import { enforcementOf } from "@groundrule/core";
import { compareSeverity, type Standard } from "@groundrule/spec";
import { Document, isMap, isSeq, parseDocument, YAMLMap, YAMLSeq } from "yaml";
import { groupByScope, type ScopeGroup, scopeHeading } from "./render.js";

export const CODERABBIT_FILE = ".coderabbit.yaml";
/** Starts every instruction Groundrule writes; entries without it belong to the team. */
export const SENTINEL = "[groundrule]";
/** Starts every custom check Groundrule writes. */
export const CHECK_PREFIX = "Groundrule ";
/** CodeRabbit allows five custom pre-merge checks (preview, Pro plan). */
export const MAX_CUSTOM_CHECKS = 5;
const SCHEMA = "# yaml-language-server: $schema=https://coderabbit.ai/integrations/schema.v2.json";
const NOTE =
  "Instructions that start with the groundrule tag, and checks named 'Groundrule …', are generated by Groundrule from .groundrule/. Edit the standards there, then run `groundrule sync`; everything else in this file is yours.";

export interface CodeRabbitEntries {
  pathInstructions: { path: string; instructions: string }[];
  customChecks: { name: string; mode: "warning"; instructions: string }[];
}

const oneLine = (s: string) => s.replace(/\s+/g, " ").trim();
const example = (
  e: Standard["spec"]["examples"] extends infer E ? E : never,
  key: "approved" | "forbidden",
) => {
  const first = (e as { approved?: unknown[]; forbidden?: unknown[] } | undefined)?.[key]?.[0];
  if (!first) return undefined;
  const code = typeof first === "string" ? first : (first as { code: string }).code;
  return oneLine(code).slice(0, 300);
};

/** A rule as one paragraph of review guidance. */
function ruleText(s: Standard): string {
  const body = oneLine(s.spec.agent.summary ?? s.spec.requirement);
  const parts = [`${s.metadata.id} (${s.spec.severity}) ${s.metadata.title}: ${body}`];
  const good = example(s.spec.examples, "approved");
  const bad = example(s.spec.examples, "forbidden");
  if (good) parts.push(`Do: ${good}`);
  if (bad) parts.push(`Don't: ${bad}`);
  return parts.join(" ");
}

/** minimatch (CodeRabbit) takes one pattern; several paths become a brace group. */
function globOf(group: ScopeGroup): string {
  if (group.key === "") return "**";
  const include =
    group.paths.length === 1 ? (group.paths[0] as string) : `{${group.paths.join(",")}}`;
  return group.exclude.length ? `${include}` : include;
}

/** A rule a reviewer can judge and no deterministic check covers, worth a pass/fail check. */
function wantsCustomCheck(s: Standard): boolean {
  const how = enforcementOf(s.spec.checks.map((c) => c.evaluator));
  return how !== "checked" && (s.spec.severity === "blocker" || s.spec.severity === "warning");
}

export function renderCodeRabbit(standards: readonly Standard[]): CodeRabbitEntries {
  const pathInstructions = groupByScope(standards).map((group) => ({
    path: globOf(group),
    instructions: [
      `${SENTINEL} Engineering standards for ${scopeHeading(group).replace(/`/g, "")}. Review changes against them; cite the rule ID in each comment.`,
      ...(group.exclude.length ? [`Not for ${group.exclude.join(", ")}.`] : []),
      ...group.standards.map(ruleText),
    ].join("\n"),
  }));
  const customChecks = [...standards]
    .filter(wantsCustomCheck)
    .sort(
      (a, b) =>
        compareSeverity(b.spec.severity, a.spec.severity) ||
        a.metadata.id.localeCompare(b.metadata.id),
    )
    .slice(0, MAX_CUSTOM_CHECKS)
    .map((s) => ({
      name: `${CHECK_PREFIX}${s.metadata.id}`.slice(0, 50),
      mode: "warning" as const,
      instructions: [
        `${SENTINEL} ${s.metadata.title}.`,
        `Pass/fail criteria: ${oneLine(s.spec.requirement)}`,
        ...(s.spec.scope.paths?.length
          ? [`Only files matching ${s.spec.scope.paths.join(", ")} count.`]
          : []),
        ...(example(s.spec.examples, "forbidden")
          ? [`Fail on code like: ${example(s.spec.examples, "forbidden")}`]
          : []),
        ...(example(s.spec.examples, "approved")
          ? [`Pass on code like: ${example(s.spec.examples, "approved")}`]
          : []),
        "This is an advisory AI check from Groundrule; deterministic checks run separately.",
      ]
        .join(" ")
        .slice(0, 10_000),
    }));
  return { pathInstructions, customChecks };
}

const ours = (node: unknown): boolean => {
  if (!isMap(node)) return false;
  const text = node.get("instructions");
  const name = node.get("name");
  return (
    (typeof text === "string" && text.startsWith(SENTINEL)) ||
    (typeof name === "string" && name.startsWith(CHECK_PREFIX))
  );
};

/**
 * `.coderabbit.yaml` with Groundrule's entries replaced (or removed, with no entries): the
 * team's own entries, keys and comments stay as they were. A missing file is created.
 */
export function mergeCodeRabbit(
  existing: string | undefined,
  entries: CodeRabbitEntries | null,
): string {
  const doc = existing?.trim() ? parseDocument(existing) : new Document(new YAMLMap());
  if (!isMap(doc.contents)) throw new Error(`${CODERABBIT_FILE} isn't a YAML mapping.`);
  if (!existing?.trim()) doc.commentBefore = ` ${NOTE}`;
  const root = doc.contents;

  const ensureMap = (parent: YAMLMap, key: string): YAMLMap => {
    const current = parent.get(key, true);
    if (isMap(current)) return current;
    const m = new YAMLMap();
    parent.set(key, m);
    return m;
  };
  const ensureSeq = (parent: YAMLMap, key: string): YAMLSeq => {
    const current = parent.get(key, true);
    if (isSeq(current)) return current;
    const s = new YAMLSeq();
    parent.set(key, s);
    return s;
  };
  const replace = (seq: YAMLSeq, items: Record<string, unknown>[]) => {
    seq.items = seq.items.filter((n) => !ours(n));
    for (const item of items) seq.add(doc.createNode(item));
  };
  const prune = (parent: YAMLMap, key: string) => {
    const node = parent.get(key, true);
    if ((isSeq(node) && node.items.length === 0) || (isMap(node) && node.items.length === 0))
      parent.delete(key);
  };

  const reviews = ensureMap(root, "reviews");
  replace(ensureSeq(reviews, "path_instructions"), entries?.pathInstructions ?? []);
  prune(reviews, "path_instructions");
  const checks = ensureMap(reviews, "pre_merge_checks");
  replace(ensureSeq(checks, "custom_checks"), entries?.customChecks ?? []);
  prune(checks, "custom_checks");
  prune(reviews, "pre_merge_checks");
  prune(root, "reviews");

  let text = doc.toString({ lineWidth: 0 });
  if (!existing?.trim() && !text.startsWith(SCHEMA)) text = `${SCHEMA}\n${text}`;
  return text.endsWith("\n") ? text : `${text}\n`;
}

/** Whether a `.coderabbit.yaml` holds entries Groundrule wrote. */
export function hasCodeRabbitEntries(text: string): boolean {
  return text.includes(SENTINEL) || text.includes(`name: ${CHECK_PREFIX}`);
}
